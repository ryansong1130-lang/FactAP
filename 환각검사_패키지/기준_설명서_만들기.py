# -*- coding: utf-8 -*-
"""
기준 파일들 맨 위에 있는 설명(따옴표 세 개 안의 글)을 모아 '문서/기준_설명서.md' 한 파일로 만들어요.

  python 기준_설명서_만들기.py

기준 파일의 설명을 고친 뒤 이 파일을 다시 실행하면 문서/기준_설명서.md 도 새로 만들어져요.
(보고서에 기준 설명을 넣을 때 이 파일을 복사해서 쓰면 편해요)
"""
import ast, os

폴더 = os.path.dirname(os.path.abspath(__file__))
순서 = [
    ("0단계와 1단계", ["단계0_답변거부", "단계1_유형분류"]),
    ("공통 기준 ①~④ (모든 유형)", ["공통1_질문답변일치", "공통2_출처답변연관성", "공통3_상위모델일치", "공통4_내부일관성"]),
    ("사실 지식형 ⑤⑥", ["사실5_핵심정보대조", "사실6_부가설명검증"]),
    ("수치 계산형 ⑤⑥", ["수치5_계산재검산", "수치6_단위조건"]),
    ("논리 추론형 ⑤⑥", ["논리5_조건대입", "논리6_임의가정"]),
    ("출처 인용형 ⑤⑥", ["출처5_출처실재", "출처6_서지정보"]),
    ("지문 이해형 ⑤⑥", ["지문5_지문근거", "지문6_핵심누락변형"]),
    ("코드 결과형 ⑤⑥", ["코드5_코드실행", "코드6_오류형식"]),
    ("전체 실행과 점수 합치기", ["../검사_실행"]),
]


def 설명_읽기(이름):
    경로 = os.path.normpath(os.path.join(폴더, "기준", 이름 + ".py"))
    with open(경로, encoding="utf-8") as f:
        return ast.get_docstring(ast.parse(f.read())) or ""


def 만들기():
    줄 = ["# 환각 검사 기준 설명서", "",
          "각 기준 파일(기준 폴더) 맨 위의 설명을 모은 문서예요. `기준_설명서_만들기.py` 로 자동으로 만들었어요.", ""]
    for 제목, 파일들 in 순서:
        줄 += [f"## {제목}", ""]
        for 이름 in 파일들:
            설명 = 설명_읽기(이름).replace("━", "").strip()
            줄 += [f"### `{os.path.basename(이름)}.py`", "", "```text", 설명, "```", ""]
    경로 = os.path.join(폴더, "문서", "기준_설명서.md")
    os.makedirs(os.path.dirname(경로), exist_ok=True)
    with open(경로, "w", encoding="utf-8") as f:
        f.write("\n".join(줄))
    print("만들었어요:", 경로)


if __name__ == "__main__":
    만들기()
