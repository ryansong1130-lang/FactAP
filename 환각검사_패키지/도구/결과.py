# -*- coding: utf-8 -*-
"""
모든 기준이 지키는 '약속' (입력과 출력의 모양)

■ 입력: 모든 기준의 검사(자료) 함수는 같은 '자료'(딕셔너리)를 받아요.
    자료 = {
        "질문": 사용자가 한 질문 (지문이나 코드가 있으면 그것까지 포함),
        "답변": 사용자가 의심하는 AI 답변,
        "출처": 그 AI가 참고한 출처 (링크나 글. 없으면 ""),
        "유형": 6개 유형 중 하나,
        "상위모델_답변들": 그 유형 상위 3개 모델에게 같은 질문을 다시 물어 받은 답변 목록,
        "검사AI": 검사 AI 3개의 판정 결과 목록 (AI_호출.검사AI_실행 의 결과. 없으면 []),
        "이전결과": 앞에서 먼저 실행된 기준들의 결과 {기준 이름: 결과},
    }

■ 출력: 모든 기준은 같은 모양의 '결과'를 돌려줘요.
    {
        "위험도": 0~1 사이 숫자 (0 = 안전, 1 = 위험) 또는 None (계산 못 함),
        "상태": "검사함" / "해당 없음" / "확인 불가",
        "근거": 사람이 읽을 수 있는 한두 문장,
        "문제_문장": 문제가 있다고 본 문장 목록 (화면에 보여 줄 것),
        "세부": 다른 기준이나 화면에서 쓸 추가 정보 (딕셔너리),
    }

  - "해당 없음": 이 질문에는 이 기준을 쓸 수 없음 (예: 출처를 입력하지 않음, 식이 없는 답변)
  - "확인 불가": 쓸 수 있는 기준인데 이번에는 확인하지 못함 (예: 인터넷 오류, API 키 없음)
  두 경우 모두 위험도는 None 이고, 점수를 합칠 때 빠져요.
"""

검사함 = "검사함"
해당없음 = "해당 없음"
확인불가 = "확인 불가"


def 결과(위험도=None, 상태=검사함, 근거="", 문제_문장=None, 세부=None):
    if 위험도 is not None:
        위험도 = round(max(0.0, min(1.0, float(위험도))), 3)
    if 상태 == 검사함 and 위험도 is None:
        상태 = 확인불가
    return {"위험도": 위험도, "상태": 상태, "근거": 근거,
            "문제_문장": list(문제_문장 or []), "세부": dict(세부 or {})}


def 빈_자료(질문="", 답변="", 출처="", 유형="", 상위모델_답변들=None, 검사AI=None):
    """시험할 때 자료를 쉽게 만들기 위한 함수"""
    return {"질문": 질문, "답변": 답변, "출처": 출처, "유형": 유형,
            "상위모델_답변들": list(상위모델_답변들 or []), "검사AI": list(검사AI or []), "이전결과": {}}


def 검사AI_값들(자료, *경로):
    """검사AI 결과 목록에서 같은 항목만 뽑아 목록으로 돌려줌. 예) 검사AI_값들(자료, "질문_일치", "판정")"""
    값들 = []
    for 판정 in 자료.get("검사AI") or []:
        값 = 판정
        for 키 in 경로:
            값 = 값.get(키) if isinstance(값, dict) else None
        if 값 is not None:
            값들.append(값)
    return 값들


def 비율(값들, 문제_값들):
    """값들 중 문제_값들에 해당하는 비율. 값이 없으면 None"""
    if not 값들:
        return None
    문제 = [v for v in 값들 if str(v).strip() in 문제_값들]
    return len(문제) / len(값들)
