def 출처_글_모으기(출처):
    """출처 칸에서 링크와 붙여 넣은 글을 나눠 본문 글을 모음. (본문 목록, 열지 못한 링크 목록)"""
    링크들 = re.findall(r"https?://[^\s<>\"')\]]+", 출처 or "")
    본문들, 실패 = [], []
    for 주소 in 링크들[:5]:
        글 = 웹_도구.웹_글_가져오기(주소)
        (본문들.append(글) if 글 and len(글) > 100 else 실패.append(주소))
    남은글 = re.sub(r"https?://\S+", " ", 출처 or "").strip()
    if len(남은글) >= 50:
        본문들.append(남은글)
    return 본문들, 실패


def 묶음_만들기(본문들, 크기=3):
    묶음 = []
    for 본문 in 본문들:
        문장들 = 문장_나누기(본문, 5)
        for i in range(0, max(1, len(문장들)), 2):
            묶음.append(" ".join(문장들[i:i + 크기]))
    return [m for m in 묶음 if m]


def _AI_판정(문장, 출처부분, 모델_ID):
    지시 = ("아래 [출처]가 [문장]을 뒷받침하는지 판정하라. '뒷받침', '반대', '언급 없음' 중 하나만 답하라.\n\n"
          f"[출처]\n{출처부분[:2500]}\n\n[문장]\n{문장}")
    try:
        답 = AI_호출.AI_부르기(모델_ID, 지시, 온도=0, 최대_토큰=20)
    except AI_호출.AI오류:
        return None
    for 값 in ("뒷받침", "반대", "언급 없음"):
        if 값 in 답:
            return 값
    return None


def 검사(자료):
    출처 = (자료.get("출처") or "").strip()
    if not 출처:
        return 결과(None, 해당없음, "출처를 입력하지 않았어요.")
    본문들, 실패 = 출처_글_모으기(출처)
    if not 본문들:
        return 결과(None, 확인불가, "출처 페이지를 열지 못했어요. 출처의 본문을 복사해서 붙여 넣어 주세요.",
                  세부={"열지_못한_링크": 실패})
    묶음 = 묶음_만들기(본문들)
    판정표 = []
    for 문장 in 문장_나누기(자료.get("답변", ""), 10):
        점수, 부분 = max(((덮는_비율(문장, m), m) for m in 묶음), default=(0.0, ""))
        if 점수 >= 설정.출처지지_기준:
            답숫자, 출처숫자 = set(숫자_뽑기(문장)), set(숫자_뽑기(부분))
            판정 = "숫자 다름" if 답숫자 and not (답숫자 & 출처숫자) else "비슷한 내용 있음"
        else:
            판정 = "출처에 없음"
        판정표.append({"문장": 문장, "1차": 판정, "겹침": round(점수, 2), "출처부분": 부분[:300]})
    if not 판정표:
        return 결과(None, 해당없음, "확인할 만한 문장이 없어요.")
    검사모델 = (자료.get("검사모델") or [None])[0]
    AI사용 = bool(검사모델 and AI_호출.키가_있나())
    for 줄 in 판정표:
        줄["2차"] = _AI_판정(줄["문장"], 줄["출처부분"], 검사모델) if AI사용 and 줄["1차"] != "비슷한 내용 있음" else None
    if AI사용:
        반대 = sum(줄["2차"] == "반대" for 줄 in 판정표)
        언급없음 = sum(줄["2차"] == "언급 없음" or (줄["2차"] is None and 줄["1차"] == "출처에 없음") for 줄 in 판정표)
    else:
        반대 = sum(줄["1차"] == "숫자 다름" for 줄 in 판정표)
        언급없음 = sum(줄["1차"] == "출처에 없음" for 줄 in 판정표)
    위험도 = (반대 + 0.5 * 언급없음) / len(판정표)
    문제 = [줄["문장"] for 줄 in 판정표 if 줄["1차"] != "비슷한 내용 있음" and 줄.get("2차") != "뒷받침"]
    근거 = (f"답변 {len(판정표)}문장 중 출처와 반대 {반대}문장, 출처에 없음 {언급없음}문장"
          + (" (검사 AI 판정 포함)" if AI사용 else " (프로그램 판정)"))
    if 실패:
        근거 += f". 열지 못한 링크 {len(실패)}개"
    return 결과(위험도, 근거=근거, 문제_문장=문제, 세부={"판정표": 판정표, "열지_못한_링크": 실패})


