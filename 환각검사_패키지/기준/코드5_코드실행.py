import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from 도구.결과 import 결과, 해당없음, 확인불가, 검사AI_값들
from 도구.글_도구 import 코드_뽑기
from 도구.코드_도구 import 코드_실행, 답변_주장_뽑기, 느슨하게, 오류라고_했나

정보 = {"번호": "⑤", "이름": "코드 직접 실행", "맡는_환각": "사실 상충", "적용_유형": "코드 결과형", "방식": "프로그램 실행"}


def _앞부분(답변):
    줄들 = [l for l in (답변 or "").splitlines() if l.strip()]
    return "\n".join(줄들[:6])


def _값이_있나(실제, 답변, 주장들):
    """실제 출력(한 덩어리)이 답변의 주장 속에 있는지"""
    느 = 느슨하게(실제)
    if not 느:
        return any(not 느슨하게(c) for c in 주장들)
    if any(느슨하게(c) == 느 for c in 주장들):
        return True
    앞 = 느슨하게(_앞부분(답변)) + "|" + "|".join(느슨하게(c) for c in 주장들)
    if len(느) >= 3:
        return 느 in 앞
    return bool(re.search(rf"(?<![0-9a-z.]){re.escape(느)}(?![0-9a-z.])", 앞))


def 비교하기(실행, 답변, 추가_주장=()):
    """실행 결과와 답변 비교 → (위험도, 근거, 문제 문장)"""
    주장들 = 답변_주장_뽑기(답변) + [c for c in 추가_주장 if c]
    했나, 이름들 = 오류라고_했나(답변)
    if 실행["상태"] == "오류":
        if 실행["오류"] in 이름들:
            return 0.0, f"실제로 {실행['오류']}가 나고, 답변도 같은 오류라고 했어요.", []
        if 했나 and not 이름들:
            return 0.5, f"실제로 {실행['오류']}가 나요. 답변은 오류라고만 하고 오류 이름은 쓰지 않았어요.", []
        말한것 = ", ".join(이름들) if 이름들 else (주장들[0][:40] if 주장들 else "알 수 없음")
        return 1.0, f"실제로는 {실행['오류']}가 나는데, 답변은 '{말한것}'(이)라고 했어요.", [f"실제: {실행['오류']} / 답변: {말한것}"]
    실제 = 실행["출력"].rstrip("\n")
    if _값이_있나(실제, 답변, 주장들):
        return 0.0, f"실제 출력 '{실제[:40]}'과 답변의 출력값이 같아요.", []
    줄들 = [l for l in 실제.splitlines() if l.strip()]
    if len(줄들) >= 2:
        맞음 = sum(_값이_있나(l, 답변, 주장들) for l in 줄들)
        if 맞음:
            위험도 = 1 - 맞음 / len(줄들)
            return 위험도, f"실제 출력 {len(줄들)}줄 중 {맞음}줄만 답변과 같아요.", [f"실제 출력: {실제[:80]}"]
    말한것 = 주장들[0][:40] if 주장들 else "찾지 못함"
    return 1.0, f"실제 출력은 '{실제[:40]}'인데, 답변은 '{말한것}'(이)라고 했어요.", [f"실제: {실제[:60]} / 답변: {말한것}"]


def 검사(자료):
    코드 = 코드_뽑기(자료.get("질문", ""))
    if not 코드.strip():
        return 결과(None, 해당없음, "질문에서 파이썬 코드를 찾지 못했어요.")
    실행 = 코드_실행(코드)
    if 실행["상태"] in ("실행 안 함", "시간 초과"):
        return 결과(None, 확인불가, 실행["메시지"], 세부={"실행": 실행, "코드": 코드})
    AI주장 = [str(x) for x in 검사AI_값들(자료, "유형별_검사", "답변_출력")]
    위험도, 근거, 문제 = 비교하기(실행, 자료.get("답변", ""), AI주장)
    return 결과(위험도, 근거=근거, 문제_문장=문제, 세부={"실행": 실행, "코드": 코드})


