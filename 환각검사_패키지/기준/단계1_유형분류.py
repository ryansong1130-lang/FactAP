_모델 = None


def _모델_가져오기():
    global _모델
    if _모델 is None:
        경로 = os.path.join(os.path.dirname(유형_분류기.__file__), "유형_분류_모델.json")
        _모델 = 유형_분류기.모델_불러오기(경로)
        _모델["설정"]["애매기준"] = 설정.유형_애매기준
    return _모델


def 확률_1순위(확신도):
    """확신도(1등과 2등 점수 차이)를 '1순위 유형이 맞을 확률'로 바꿈 (1순위와 2순위 둘 중에서). 설정.유형_확률_기울기 참고"""
    return round(1 / (1 + math.exp(-설정.유형_확률_기울기 * 확신도)), 3)


def 유형_정하기(질문, 답변=""):
    r = 유형_분류기.분류하기(_모델_가져오기(), 질문, 답변)
    return {"유형": r["유형"], "2순위": r["2순위"], "확신도": r["확신도"], "애매함": r["애매함"],
            "1순위_확률": 확률_1순위(r["확신도"]),
            "유형_불일치": r.get("유형_불일치", False), "질문만_유형": r.get("질문만_유형")}


