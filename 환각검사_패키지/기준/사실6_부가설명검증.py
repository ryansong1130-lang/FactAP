정보 = {"번호": "⑥", "이름": "부가 설명 검증", "맡는_환각": "사실 상충", "적용_유형": "사실 지식형", "방식": "웹 검색(위키백과) + 검사 AI"}


def AI_덧붙인_사실(자료):
    """검사 AI들이 뽑은 덧붙인 문장을 비슷한 것끼리 묶어 다수결. [(문장, 다수 판정 또는 None)]"""
    묶음 = []          # [[문장, [판정들]]]
    for 목록 in 검사AI_값들(자료, "유형별_검사", "덧붙인_사실"):
        if not isinstance(목록, list):
            continue
        for x in 목록:
            if not isinstance(x, dict) or not str(x.get("문장", "")).strip():
                continue
            문장, 판정 = str(x["문장"]).strip(), str(x.get("판정", "")).strip()
            for 칸 in 묶음:
                if 비슷한_정도(칸[0], 문장) >= 0.5:
                    칸[1].append(판정); break
            else:
                묶음.append([문장, [판정]])
    결과들 = []
    for 문장, 판정들 in 묶음:
        최다 = max(set(판정들), key=판정들.count)
        결과들.append((문장, 최다 if 판정들.count(최다) * 2 > len(판정들) or len(판정들) == 1 else None))
    return 결과들


def 규칙_덧붙인_사실(답변):
    문장들 = [s for s in 문장_나누기(답변, 1)[1:] if len(re.sub(r"\s", "", s)) >= 10]   # 첫 문장(핵심 답)은 빼기
    고름 = [s for s in 문장들 if re.search(r"\d|\(|「|『|\"|“", s)]
    return [(s, None) for s in 고름[:8]]


def 위키_묶음(본문, 크기=3):
    문장들 = 문장_나누기(본문 or "", 5)
    return [" ".join(문장들[i:i + 크기]) for i in range(0, max(1, len(문장들)), 2) if 문장들[i:i + 크기]]


def 위키와_맞추기(문장, 묶음):
    점수, 부분 = max(((덮는_비율(문장, m), m) for m in 묶음), default=(0.0, ""))
    if 점수 < 설정.출처지지_기준:
        return "확인 안 됨", 부분
    문장수 = {x for x in 숫자_뽑기(문장) if x >= 10}            # 1, 2 같은 작은 수(순서)는 빼고
    if 문장수 and not (문장수 & set(숫자_뽑기(부분))):
        return "숫자 다름", 부분
    return "맞음", 부분


def _위키_본문(자료):
    앞 = ((자료.get("이전결과") or {}).get("핵심 정보 대조") or {}).get("세부") or {}
    if 앞.get("위키_본문"):
        return 앞.get("위키_제목"), 앞["위키_본문"]
    from 기준 import 사실5_핵심정보대조 as 오
    값들, 검색어, _ = 오.핵심정보_정하기(자료)
    return 오.위키_가져오기(검색어, 값들) if 검색어 else (None, None)


def 검사(자료):
    AI목록 = AI_덧붙인_사실(자료)
    대상 = AI목록 or 규칙_덧붙인_사실(자료.get("답변", ""))
    if not 대상:
        return 결과(None, 해당없음, "답변에 덧붙인 세부 설명이 없어요.")
    제목, 본문 = _위키_본문(자료)
    묶음 = 위키_묶음(본문) if 본문 else []
    if not AI목록 and not 묶음:
        return 결과(None, 확인불가, "검사 AI 결과가 없고 위키백과도 열지 못해 확인하지 못했어요.")
    표, 점수들 = [], []
    for 문장, AI판정 in 대상:
        위키판정, 부분 = 위키와_맞추기(문장, 묶음) if 묶음 else ("위키백과 없음", "")
        if AI판정 == "틀림":
            점수 = 1.0
        elif 위키판정 == "숫자 다름":
            점수 = 0.7
        elif AI판정 == "맞음" or 위키판정 == "맞음":
            점수 = 0.0
        else:
            점수 = 0.3
        점수들.append(점수)
        표.append({"문장": 문장, "검사AI": AI판정, "위키백과": 위키판정, "점수": 점수, "위키_부분": 부분[:200]})
    위험도 = sum(점수들) / len(점수들)
    틀림 = sum(p >= 0.7 for p in 점수들)
    근거 = f"덧붙인 설명 {len(표)}문장 중 틀렸거나 숫자가 다른 문장 {틀림}개, 확인 안 된 문장 {sum(p == 0.3 for p in 점수들)}개"
    근거 += f" (비교: {'검사 AI' if AI목록 else ''}{' + ' if AI목록 and 묶음 else ''}{('위키백과 ' + repr(제목)) if 묶음 else ''})."
    문제 = [f"{줄['문장']} ({'검사 AI: 틀림' if 줄['검사AI'] == '틀림' else '위키백과와 숫자가 다름'})" for 줄 in 표 if 줄["점수"] >= 0.7]
    return 결과(위험도, 근거=근거, 문제_문장=문제, 세부={"문장별": 표})


