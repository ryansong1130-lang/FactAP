# ------------------------------------------------------------------ 안전한 계산기 (숫자와 사칙연산, 거듭제곱만)
_연산 = {ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul, ast.Div: operator.truediv,
        ast.Pow: operator.pow, ast.USub: operator.neg, ast.UAdd: operator.pos}


def 계산(식):
    """'(72*5)-3' 같은 식을 계산. 계산할 수 없으면 None"""
    try:
        나무 = ast.parse(식, mode="eval")
    except SyntaxError:
        return None

    def 풀기(n):
        if isinstance(n, ast.Expression):
            return 풀기(n.body)
        if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)):
            return n.value
        if isinstance(n, ast.BinOp) and type(n.op) in _연산:
            왼, 오 = 풀기(n.left), 풀기(n.right)
            if isinstance(n.op, ast.Pow) and abs(오) > 100:
                raise ValueError("너무 큰 거듭제곱")
            return _연산[type(n.op)](왼, 오)
        if isinstance(n, ast.UnaryOp) and type(n.op) in _연산:
            return _연산[type(n.op)](풀기(n.operand))
        raise ValueError("계산할 수 없는 식")
    try:
        return float(풀기(나무))
    except Exception:
        return None


# ------------------------------------------------------------------ 식 정리와 찾기
def 식_정리(글):
    글 = 글 or ""
    글 = 글.replace("{,}", ",").replace("\\,", "")
    글 = re.sub(r"\\[dt]?frac\{([^{}]*)\}\{([^{}]*)\}", r"((\1)/(\2))", 글)
    글 = re.sub(r"\\sqrt\{([^{}]*)\}", r"((\1)**0.5)", 글)
    for 옛, 새 in (("\\times", "*"), ("\\cdot", "*"), ("\\div", "/"), ("\\approx", "≈"), ("\\left", ""),
                  ("\\right", ""), ("×", "*"), ("·", "*"), ("÷", "/"), ("−", "-"), ("–", "-"), ("^", "**"), ("{", "("), ("}", ")")):
        글 = 글.replace(옛, 새)
    글 = re.sub(r"[⁰¹²³⁴⁵⁶⁷⁸⁹]+", lambda m: "**" + m.group(0).translate(_윗첨자), 글)
    글 = re.sub(r"\\[a-zA-Z]+", " ", 글)
    글 = re.sub(r"[$*]{0,2}\*\*(?!\d|\()", " ", 글)         # **굵게** 표시 지우기 (거듭제곱 ** 는 남김)
    글 = re.sub(r"(?<=\d),(?=\d{3}(?!\d))", "", 글)            # 1,000 → 1000
    글 = re.sub(r"(\d+(?:\.\d+)?)\s*%", r"(\1/100)", 글)       # 5% → (5/100)
    글 = re.sub(r"(?<=\d)\s*[xX]\s*(?=\d)", "*", 글)          # 3 x 4 → 3*4
    return 글


_윗첨자 = str.maketrans("⁰¹²³⁴⁵⁶⁷⁸⁹", "0123456789")
_항 = r"[\d(][\d\s.+\-*/()]*[\d)]|\d"
_식줄 = re.compile(rf"(?<![A-Za-z가-힣\d.])((?:{_항})(?:\s*(?:=|≈)\s*(?:약\s*)?(?:{_항}))+)(?![A-Za-z\d])")


def _자릿수_허용(값_글):
    값_글 = 값_글.strip()
    if re.fullmatch(r"-?\d+\.\d+", 값_글):
        return 10 ** -len(값_글.split(".")[1])
    return 1 if re.fullmatch(r"-?\d+", 값_글) else 1e-9


def 식들_검사(답변):
    """돌려주는 값: [(원래 식, 왼쪽 값, 오른쪽 값, 맞음 여부)]"""
    결과들 = []
    for 줄 in 식_정리(답변).splitlines():
        for m in _식줄.finditer(줄):
            앞 = 줄[:m.start()].rstrip()
            if 앞 and re.search(r"[A-Za-z*/+\-^]$", 앞):
                continue                                  # a² + 5² = 13² 처럼 문자가 들어간 식의 일부
            조각 = re.split(r"\s*(=|≈)\s*(?:약\s*)?", m.group(1))
            항들, 기호들 = 조각[0::2], 조각[1::2]
            for i in range(len(기호들)):
                왼, 오 = 항들[i].strip(), 항들[i + 1].strip()
                if not re.search(r"\d\s*[-+*/]|\)\s*[-+*/]|[-+*/]\s*[\d(]", 왼):
                    continue                              # 왼쪽이 그냥 숫자면 비교할 계산이 없음
                a, b = 계산(왼), 계산(오)
                if a is None or b is None:
                    continue
                if 기호들[i] == "≈":
                    허용 = max(abs(a) * 설정.어림_허용오차, _자릿수_허용(오))
                elif re.search(r"[-+*/]", 오.lstrip("-")):
                    허용 = 1e-9 * max(1, abs(a))
                else:
                    허용 = _자릿수_허용(오) + 1e-9 * max(1, abs(a))
                결과들.append((f"{왼} {기호들[i]} {오}", a, b, abs(a - b) <= 허용))
    return 결과들


def 질문_식_계산(질문):
    """질문이 바로 계산식인 경우 그 값. 예) '4,837 × 2,916은 얼마인가요?', '2의 30제곱은?'"""
    m = re.search(r"(\d+)\s*의\s*(\d+)\s*제곱", 질문 or "")
    if m:
        return f"{m.group(1)}의 {m.group(2)}제곱", 계산(f"{m.group(1)}**{m.group(2)}")
    정리 = 식_정리(질문)
    m = re.search(rf"(?<![A-Za-z가-힣\d.])({_항})\s*(?:은|는|의 값|을 계산|를 계산|=\s*\?)", 정리)
    if m and re.search(r"[\d)]\s*[-+*]", m.group(1)) and re.search(r"얼마|계산|값|구하", 질문 or ""):
        return m.group(1).strip(), 계산(m.group(1))
    return None, None


def 검사(자료):
    답변 = 자료.get("답변", "")
    식들 = 식들_검사(답변)
    틀림 = [f"{식} (다시 계산하면 {왼:g})" for 식, 왼, 오, 맞음 in 식들 if not 맞음]
    질문식, 질문값 = 질문_식_계산(자료.get("질문", ""))
    최종 = None
    if 질문값 is not None:
        최종글 = 최종답_뽑기(답변, "수치 계산형")
        후보 = 숫자_뽑기(re.sub(r"\*\*\d+", "", 식_정리(최종글)))      # 거듭제곱 지수는 빼고
        if 후보:
            최종 = 후보[-1]
            if not any(abs(x - 질문값) <= 1e-9 * max(1, abs(질문값)) for x in 후보):
                틀림.insert(0, f"질문의 식 {질문식} = {질문값:,.10g} 인데 답변의 최종 답은 '{최종글[:30]}'")
    확인수 = len(식들) + (1 if 최종 is not None else 0)
    if not 확인수:
        return 결과(None, 해당없음, "다시 계산할 수 있는 식을 찾지 못했어요.")
    if 틀림:
        return 결과(1.0, 근거=f"식 {확인수}개를 다시 계산했더니 {len(틀림)}개가 틀렸어요.", 문제_문장=틀림,
                  세부={"식들": 식들, "질문_식": 질문식})
    return 결과(0.0, 근거=f"식 {확인수}개를 다시 계산했고 모두 맞아요.", 세부={"식들": 식들, "질문_식": 질문식})


