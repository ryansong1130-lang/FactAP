import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from 도구.결과 import 결과, 해당없음, 확인불가, 검사AI_값들
from 도구.글_도구 import 마크다운_지우기, 덮는_비율, 숫자_뽑기
from 도구 import 웹_도구

정보 = {"번호": "⑤", "이름": "핵심 정보 대조", "맡는_환각": "사실 상충", "적용_유형": "사실 지식형", "방식": "웹 검색(위키백과) + 규칙"}

묻는말 = r"(은|는|이|가)?\s*(무엇|누구|언제|어디|몇|어느|어떤)[^?]*\??$"


def 핵심정보_정하기(자료):
    """([핵심 값들], 검색어, 정한 방법)"""
    AI목록 = [목록 for 목록 in 검사AI_값들(자료, "유형별_검사", "핵심정보") if isinstance(목록, list)]
    값들 = []
    for 목록 in AI목록:
        for x in 목록:
            값 = str(x.get("값", "") if isinstance(x, dict) else x).strip()
            if 값 and 값 not in 값들:
                값들.append(값)
    검색어들 = [str(x).strip() for x in 검사AI_값들(자료, "유형별_검사", "검색어") if str(x).strip()]
    if 값들 and 검색어들:
        return 값들[:6], max(set(검색어들), key=검색어들.count), "검사 AI"
    답변 = 자료.get("답변", "")
    앞 = "\n".join([l for l in 답변.splitlines() if l.strip()][:2])
    값들 = [마크다운_지우기(x).strip() for x in re.findall(r"\*\*(.+?)\*\*", 앞) if len(마크다운_지우기(x).strip()) <= 20]
    값들 += [y for y in re.findall(r"(?<!\d)(1[0-9]{3}|20[0-9]{2})(?!\d)", 앞)
            if y not in 자료.get("질문", "") and not any(y in v for v in 값들)]
    값들 = list(dict.fromkeys(v for v in 값들 if v))
    검색어 = re.sub(묻는말, "", 마크다운_지우기(자료.get("질문", "")).strip().splitlines()[0] if 자료.get("질문") else "").strip()
    return 값들[:6], 검색어, "프로그램 규칙"


def _정리(글):
    return re.sub(r"\s|[·,.'\"「」『』《》]", "", 글 or "")


def 본문에_있나(값, 본문):
    값 = re.sub(r"\(.*?\)", "", 값).strip()          # 괄호 속 한자·영어 빼기
    if not 값:
        return True
    수들 = [x for x in re.findall(r"\d+", 값)]
    if 수들:
        본문수 = set(re.findall(r"\d+", 본문.replace(",", "")))
        return all(x in 본문수 for x in 수들)
    return _정리(값) in _정리(본문) or 덮는_비율(값, 본문) >= 0.8


def 위키_가져오기(검색어, 값들):
    제목, 본문 = 웹_도구.위키백과_찾기(검색어)
    if not 본문 and 값들:
        제목, 본문 = 웹_도구.위키백과_찾기(re.sub(r"\(.*?\)", "", 값들[0]).strip())
    return 제목, 본문


def 검사(자료):
    값들, 검색어, 방법 = 핵심정보_정하기(자료)
    if not 값들:
        return 결과(None, 해당없음, "답변에서 대조할 핵심 정보(이름, 연도 등)를 찾지 못했어요.")
    제목, 본문 = 위키_가져오기(검색어, 값들)
    if not 본문:
        return 결과(None, 확인불가, f"위키백과에서 '{검색어}' 문서를 가져오지 못했어요.", 세부={"핵심정보": 값들, "검색어": 검색어})
    대조 = [(v, 본문에_있나(v, 본문)) for v in 값들]
    없음 = [v for v, 있음 in 대조 if not 있음]
    위험도 = 0.8 * len(없음) / len(대조)
    근거 = (f"핵심 정보 {len(대조)}개를 위키백과 '{제목}' 문서와 대조했더니 {len(대조) - len(없음)}개가 문서에 있어요"
          f" (핵심 정보 정한 방법: {방법}).")
    return 결과(위험도, 근거=근거, 문제_문장=[f"위키백과 '{제목}' 문서에 없음: {v}" for v in 없음],
              세부={"핵심정보": 값들, "검색어": 검색어, "위키_제목": 제목, "위키_본문": 본문[:20000], "대조": 대조})


