import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from 도구.결과 import 결과, 검사AI_값들, 비율
from 도구.글_도구 import 문장_나누기, 마크다운_지우기, 숫자_뽑기

정보 = {"번호": "④", "이름": "답변 내부 일관성", "맡는_환각": "맥락 상충", "적용_유형": "공통", "방식": "규칙 + 검사 AI"}

한글숫자 = {"한": 1, "하나": 1, "두": 2, "둘": 2, "세": 3, "셋": 3, "네": 4, "넷": 4, "다섯": 5, "여섯": 6,
          "일곱": 7, "여덟": 8, "아홉": 9, "열": 10}
단위 = r"(명|개|권|번|살|점|마리|대|곳|가지|년|회)"
결론표시 = r"따라서|그러므로|결론적으로|결론은|최종|정답은|답은"
고쳐말하기 = (r"정정(합니다|하여|하겠|드립)|앞서 (생각|말씀|드린|답한|제시)[^.\n]{0,20}(였으나|했으나|지만|은 틀|는 틀)"
          r"|혼동을 드려|다시 말씀드리면|목록 오류|오류 확인 중|잘못 (말씀|설명|계산)(드렸|했)|제가 (앞에서|위에서) (틀|잘못)")


# ------------------------------------------------------------------ 규칙 1) 결론 비교
def _굵은_답(줄):
    return [마크다운_지우기(x).strip(" :：`'\"") for x in re.findall(r"\*\*(.+?)\*\*", 줄)]


def _종류(값):
    """비교할 수 있는 짧은 답인지: '선택지' / '숫자' / None"""
    값 = re.sub(r"^(정답|답|출력 ?결과)\s*[:：]?\s*", "", 값).strip()
    if re.fullmatch(r"\(?[가-하]\)?|[A-E]|[①-⑩]", 값):
        return "선택지"
    if len(값) <= 12 and 숫자_뽑기(값) and not re.search(r"[×x*+=/÷]|\^", 값):
        return "숫자"
    return None


def 결론_모순(답변):
    줄들 = [l for l in (답변 or "").splitlines() if l.strip()]
    if len(줄들) < 4:
        return None
    첫 = 줄들[0]
    if not re.search(r"(입니다|이다|예요|이에요)\.?\s*$|정답|답\s*[은:]|출력", 첫):
        return None
    끝후보 = [l for l in 줄들[len(줄들) // 2:] if re.search(결론표시, l)]
    if not 끝후보:
        return None
    끝 = 끝후보[-1]
    앞값 = [(v, _종류(v)) for v in _굵은_답(첫) if _종류(v)]
    뒷값 = [(v, _종류(v)) for v in _굵은_답(끝) if _종류(v)]
    for 가, 종류가 in 앞값:
        for 나, 종류나 in 뒷값:
            if 종류가 != 종류나:
                continue
            if 종류가 == "선택지" and re.sub(r"[()]", "", 가) != re.sub(r"[()]", "", 나):
                return f"처음 결론 '{가}' ↔ 마지막 결론 '{나}'"
            if 종류가 == "숫자" and not (set(숫자_뽑기(가)) & set(숫자_뽑기(나))):
                return f"처음 결론 '{가}' ↔ 마지막 결론 '{나}'"
    return None


# ------------------------------------------------------------------ 규칙 2) 고쳐 말하기 표현
def 고쳐말하기_찾기(답변):
    글 = 답변 or ""
    찾음 = [m.group(0) for m in re.finditer(고쳐말하기, 글)]
    if "(X)" in 글 and "(O)" not in 글:          # O/X 설명이 아닌데 (X)로 자기 말을 지운 경우
        찾음.append("(X)")
    문장들 = [s for s in 문장_나누기(글, 4) if any(x in s for x in 찾음)]
    return 문장들[:3] if 찾음 else []


# ------------------------------------------------------------------ 규칙 3) 같은 대상의 숫자 비교
def 숫자_모순(답변):
    글 = 마크다운_지우기(답변)
    for 말, 수 in 한글숫자.items():
        글 = re.sub(rf"(?<![가-힣]){말} ?(?={단위})", f"{수}", 글)
    값들 = {}
    for 문장 in 문장_나누기(글, 4):
        if re.search(r"가정|만약|라면|경우|이면|(?<!드리)면,", 문장):
            continue
        m = re.search(rf"(\d+)\s*{단위}\s*(?:입니다|이다|뿐입니다|이에요|예요)", 문장)
        if not m:
            continue
        주어 = re.findall(r"([가-힣]{2,8})(?:은|는)\s", 문장[:m.start()])
        if 주어:
            값들.setdefault((주어[-1], m.group(2)), set()).add(m.group(1))
    return [f"'{대상}' {', '.join(sorted(수들, key=int))}{단}" for (대상, 단), 수들 in 값들.items() if len(수들) > 1]


# ------------------------------------------------------------------ 검사
def 검사(자료):
    답변 = 자료.get("답변", "")
    결론 = 결론_모순(답변)
    고침 = 고쳐말하기_찾기(답변)
    숫자 = 숫자_모순(답변)
    점수들 = [p for p, 있음 in ((0.8, 결론), (0.6, 고침), (0.4, 숫자)) if 있음]
    규칙점수 = (max(점수들) + (0.2 if len(점수들) >= 2 else 0)) if 점수들 else 0.0
    판정들 = 검사AI_값들(자료, "앞뒤_모순", "판정")
    AI비율 = 비율(판정들, {"있음"})
    AI문장 = [p.get("문장") for p in 검사AI_값들(자료, "앞뒤_모순")
            if isinstance(p, dict) and p.get("판정") == "있음" and p.get("문장")]
    위험도 = max(규칙점수, AI비율 or 0)
    근거 = []
    if 결론: 근거.append("처음 결론과 마지막 결론이 달라요")
    if 고침: 근거.append("답변이 스스로 앞의 말을 고쳐 말해요")
    if 숫자: 근거.append("같은 대상에 다른 숫자를 말해요: " + "; ".join(숫자[:3]))
    if AI비율 is not None:
        근거.append(f"검사 AI {len(판정들)}개 중 {round(AI비율 * len(판정들))}개가 '모순 있음'으로 판정")
    else:
        근거.append(("모순을 찾지 못했어요. " if not 점수들 else "") + "검사 AI 없이 프로그램 규칙으로만 확인했어요")
    return 결과(위험도, 근거=". ".join(근거) + ".", 문제_문장=([결론] if 결론 else []) + 고침 + 숫자 + AI문장,
              세부={"결론_모순": 결론, "고쳐_말하기": 고침, "숫자_모순": 숫자, "AI_판정들": 판정들})


