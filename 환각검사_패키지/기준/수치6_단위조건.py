정보 = {"번호": "⑥", "이름": "단위·조건 확인", "맡는_환각": "입력 상충", "적용_유형": "수치 계산형", "방식": "규칙 + 검사 AI"}

# 단위 묶음: 같은 묶음 안에서 다른 단위로 답하면 '단위를 어김'으로 봐요. (단위를 아예 안 쓴 것은 어김으로 보지 않아요)
단위_묶음 = {
    "길이": ["mm", "cm", "m", "km"],
    "넓이": ["mm²", "cm²", "m²", "km²"],
    "속력": ["m/s", "km/h"],
    "무게": ["mg", "g", "kg", "t"],
    "온도": ["°C", "°F"],
}
_단위_글 = r"(km²|cm²|mm²|m²|km/h|m/s|km|cm|mm|kg|mg|°C|°F|(?<![a-zA-Z])m(?![a-zA-Z²/])|(?<![a-zA-Z])g(?![a-zA-Z])|(?<![a-zA-Z])t(?![a-zA-Z]))"


def 단위_정리(글):
    """답변 속 단위 표기를 한 가지 모양으로 맞춤. 예) \\text{cm}^2 → cm², ℃ → °C, 섭씨 → °C"""
    글 = 마크다운_지우기(글 or "")
    for 옛 in ("\\(", "\\)", "\\[", "\\]", "\\,", "{", "}"):
        글 = 글.replace(옛, "")
    글 = re.sub(r"\s*\^\s*2", "²", 글).replace("㎠", "cm²").replace("㎡", "m²").replace("℃", "°C").replace("℉", "°F")
    글 = re.sub(r"화씨\s*([\d.]+)\s*도", r"\1°F", 글)
    글 = re.sub(r"섭씨\s*([\d.]+)\s*도", r"\1°C", 글)
    return 글


def _물은_단위(질문):
    질문 = 단위_정리(질문)
    if re.search(r"초속\s*몇\s*m(?![a-zA-Z])", 질문):
        return "속력", {"m/s", "m"}
    if re.search(r"시속\s*몇\s*km", 질문):
        return "속력", {"km/h", "km"}
    if re.search(r"화씨\s*몇\s*도", 질문):
        return "온도", {"°F"}
    if re.search(r"섭씨\s*몇\s*도", 질문):
        return "온도", {"°C"}
    m = re.search(r"몇\s*" + _단위_글, 질문)
    if m:
        for 묶음, 단위들 in 단위_묶음.items():
            if m.group(1) in 단위들:
                return 묶음, {m.group(1)}
    return None, None


def 조건_찾기(질문):
    질문 = 질문 or ""
    조건 = []
    묶음, 인정 = _물은_단위(질문)
    if 묶음:
        조건.append(("단위", "/".join(sorted(인정)), (묶음, 인정)))
    if re.search(r"몇\s*(%|퍼센트)", 질문):
        조건.append(("퍼센트", "%", None))
    if re.search(r"기약\s*분수", 질문):
        조건.append(("기약분수", "기약분수", None))
    m = re.search(r"소수\s*(첫째|둘째|셋째|\d+)\s*자리", 질문)
    if m:
        자리 = {"첫째": 1, "둘째": 2, "셋째": 3}.get(m.group(1)) or int(m.group(1))
        조건.append(("자리수", f"소수 {자리}자리", 자리))
    if re.search(r"원\s*단위까지|정수로|자연수로", 질문):
        조건.append(("자리수", "정수(원 단위)", 0))
    if re.search(r"몇\s*시간\s*몇\s*분", 질문):
        조건.append(("모양", "○시간 ○분", r"\d+\s*시간\s*\d+\s*분"))
    if re.search(r"원주율[은는을를]?\s*3\.14", 질문):
        조건.append(("원주율", "원주율 3.14", None))
    return 조건


def 답_부분(답변):
    원문 = 답변 or ""
    줄들 = [l for l in 원문.splitlines() if l.strip()]
    굵게 = re.findall(r"\*\*(.+?)\*\*", 원문)
    return [단위_정리(x) for x in [최종답_뽑기(원문, "수치 계산형")] + 굵게[:3] + 줄들[-2:] if x]


def _분수들(글):
    글 = re.sub(r"\\[dt]?frac\{(\d+)\}\{(\d+)\}", r"\1/\2", 글)
    return [(int(a), int(b)) for a, b in re.findall(r"(?<![\d.])(\d+)\s*/\s*(\d+)(?![\d.])", 글)]


def 조건_확인(조건, 답변):
    """어긴 조건 목록"""
    부분 = 답_부분(답변)
    전부 = " ".join(부분)
    어김 = []
    for 종류, 이름, 값 in 조건:
        if 종류 == "단위":
            묶음, 인정 = 값
            최종 = 단위_정리(최종답_뽑기(답변, "수치 계산형"))
            쓴단위 = re.findall(r"\d\s*" + _단위_글, 최종)
            최종수 = re.findall(r"\d[\d,]*(?:\.\d+)?", 최종)
            if not 쓴단위 and 최종수:                  # 최종 답에 단위가 없으면, 같은 숫자 바로 뒤에 붙은 단위만 봄
                쓴단위 = re.findall(re.escape(최종수[-1]) + r"\s*" + _단위_글, 전부)
            같은묶음 = [u for u in 쓴단위 if u in 단위_묶음[묶음] or (묶음 == "속력" and u in ("m", "km"))]
            if 같은묶음 and not (set(같은묶음) & 인정):
                어김.append(f"질문은 {이름} 단위로 물었는데 답은 {같은묶음[-1]} 단위예요")
        elif 종류 == "퍼센트":
            최종 = 단위_정리(최종답_뽑기(답변, "수치 계산형"))
            if "%" not in 최종 and "퍼센트" not in 최종 and re.fullmatch(r"\s*0?\.\d+\s*", re.sub(r"[^\d.\s]", "", 최종)):
                어김.append("몇 %인지 물었는데 답을 소수로만 썼어요")
        elif 종류 == "기약분수":
            분수 = [f for f in _분수들(답변 if not 부분 else 전부)]
            if 분수 and all(math.gcd(a, b) > 1 for a, b in 분수[-1:]):
                a, b = 분수[-1]
                어김.append(f"기약분수로 답하라고 했는데 {a}/{b}는 더 약분할 수 있어요")
            elif not 분수 and re.search(r"\d\.\d", 전부):
                어김.append("기약분수로 답하라고 했는데 소수로 답했어요")
        elif 종류 == "자리수":
            수들 = re.findall(r"\d[\d,]*(?:\.\d+)?", 최종답_뽑기(답변, "수치 계산형"))
            if 수들:
                소수자리 = len(수들[-1].split(".")[1]) if "." in 수들[-1] else 0
                if 소수자리 > 값:
                    어김.append(f"{이름}까지 답하라고 했는데 소수 {소수자리}자리로 답했어요")
        elif 종류 == "모양" and not re.search(값, 전부):
            어김.append(f"'{이름}' 모양으로 답하지 않았어요")
        elif 종류 == "원주율" and re.search(r"π|\\pi", 전부) and not re.search(r"\d+\.\d+", 전부):
            어김.append("원주율을 3.14로 계산하라고 했는데 π가 남은 식으로 답했어요")
    return 어김


def 검사(자료):
    조건 = 조건_찾기(자료.get("질문", ""))
    어김 = 조건_확인(조건, 자료.get("답변", "")) if 조건 else []
    AI표 = [str(x).strip() for x in 검사AI_값들(자료, "유형별_검사", "조건_지킴") if str(x).strip() in ("예", "아니오")]
    AI비율 = 비율(AI표, {"아니오"})
    if not 조건 and AI비율 is None:
        return 결과(None, 해당없음, "질문에서 확인할 단위나 조건을 찾지 못했어요.")
    규칙점수 = 0.0 if not 어김 else (0.7 if len(어김) == 1 else 1.0)
    위험도 = max(규칙점수, AI비율 or 0)
    근거 = (f"질문의 조건 {len(조건)}개 중 {len(어김)}개를 어겼어요." if 조건 else "프로그램이 찾은 조건은 없어요.")
    if 조건 and not 어김:
        근거 = f"질문의 조건 {len(조건)}개({', '.join(c[1] for c in 조건)})를 모두 지켰어요."
    if AI비율 is not None:
        근거 += f" 검사 AI {len(AI표)}개 중 {round(AI비율 * len(AI표))}개가 '조건을 어김'으로 판정했어요."
    AI근거 = [str(p.get("근거")) for p in 검사AI_값들(자료, "유형별_검사")
            if isinstance(p, dict) and str(p.get("조건_지킴", "")).strip() == "아니오" and p.get("근거")]
    return 결과(위험도, 근거=근거, 문제_문장=어김 + AI근거, 세부={"조건": [c[1] for c in 조건], "어긴_조건": 어김})


