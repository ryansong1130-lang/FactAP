정보 = {"번호": "⑤", "이름": "조건 대입 확인", "맡는_환각": "사실 상충, 입력 상충", "적용_유형": "논리 추론형", "방식": "규칙 + 검사 AI"}

_이름 = r"([A-Z]|[가-힣]{1,4}?)(?:책|이|가|은|는)?"
_조사 = r"(?:책)?(?:은|는|이|가)\s*"


def _항목_찾기(질문):
    """질문에 나열된 대상들. 예) '국어, 수학, 영어, 과학 책' → [국어, 수학, 영어, 과학], 'A, B, C, D, E' → [A..E]"""
    for m in re.finditer(r"((?:[A-Z]|[가-힣]{1,4})(?:\s*,\s*(?:[A-Z]|[가-힣]{1,4})){2,})", 질문):
        항목 = [x.strip() for x in m.group(1).split(",")]
        if len(set(항목)) == len(항목):
            return 항목
    return []


def 순서_조건_찾기(질문, 항목):
    if not 항목:
        return []
    이름 = "(" + "|".join(map(re.escape, sorted(항목, key=len, reverse=True))) + ")"
    조건 = []
    for 문장 in re.split(r"(?<=[.다])\s+", 질문):
        for m in re.finditer(이름 + _조사 + r"맨\s*(위|앞)(?:에|입)", 문장):
            조건.append((m.group(0), "처음", m.group(1)))
        for m in re.finditer(이름 + _조사 + r"맨\s*(아래|뒤|끝)(?:에|입)", 문장):
            조건.append((m.group(0), "끝", m.group(1)))
        for m in re.finditer(이름 + _조사 + r"맨\s*(위|앞)(?:이|가)?\s*(?:아니|아닙|아님)", 문장):
            조건.append((m.group(0), "처음아님", m.group(1)))
        for m in re.finditer(이름 + _조사 + r"맨\s*(아래|뒤|끝)(?:이|가)?\s*(?:아니|아닙|아님)", 문장):
            조건.append((m.group(0), "끝아님", m.group(1)))
        for m in re.finditer(이름 + _조사 + r"(?:정가운데|한가운데)?\s*\(?\s*(\d)\s*번째", 문장):
            조건.append((m.group(0), "번째", m.group(1), int(m.group(2))))
        for m in re.finditer(이름 + _조사 + r"(?:정가운데|한가운데)(?!\s*\(?\s*\d)", 문장):
            조건.append((m.group(0), "가운데", m.group(1)))
        for m in re.finditer(이름 + _조사 + 이름 + r"(?:책)?(?:의)?\s*바로\s*(위|앞|아래|뒤)", 문장):
            조건.append((m.group(0), "바로", m.group(1), m.group(2), m.group(3)))
        for m in re.finditer(이름 + _조사 + 이름 + r"(?:책)?보다\s*(위|앞|아래|뒤)", 문장):
            조건.append((m.group(0), "보다", m.group(1), m.group(2), m.group(3)))
    return 조건


def 답_순서_찾기(답변, 항목):
    """답변 뒷부분에서 항목을 모두 한 번씩 쓴 순서(가장 마지막 것)"""
    글 = 마크다운_지우기(답변).replace("`", "")
    이름 = "|".join(map(re.escape, sorted(항목, key=len, reverse=True)))
    찾은 = None
    for m in re.finditer(rf"(?:{이름})(?:책)?(?:\s*(?:,|→|->|-|>|/|ㆍ|·)\s*(?:{이름})(?:책)?){{{len(항목) - 1}}}", 글):
        순서 = re.findall(이름, m.group(0))
        if len(순서) == len(항목) and set(순서) == set(항목):
            찾은 = 순서
    return 찾은


def 대입하기(조건, 순서, 위부터=True):
    """각 조건의 만족/위반. 위부터=True 이면 순서[0]이 맨 위(맨 앞)"""
    자리 = {x: i for i, x in enumerate(순서)}
    n = len(순서)
    결과들 = []
    for c in 조건:
        문장, 종류 = c[0], c[1]
        try:
            if 종류 == "처음": 맞음 = 자리[c[2]] == 0
            elif 종류 == "끝": 맞음 = 자리[c[2]] == n - 1
            elif 종류 == "처음아님": 맞음 = 자리[c[2]] != 0
            elif 종류 == "끝아님": 맞음 = 자리[c[2]] != n - 1
            elif 종류 == "번째": 맞음 = 자리[c[2]] == c[3] - 1
            elif 종류 == "가운데": 맞음 = n % 2 == 1 and 자리[c[2]] == n // 2
            elif 종류 == "바로":
                차 = -1 if c[4] in ("위", "앞") else 1
                맞음 = 자리[c[2]] == 자리[c[3]] + 차
            elif 종류 == "보다":
                맞음 = 자리[c[2]] < 자리[c[3]] if c[4] in ("위", "앞") else 자리[c[2]] > 자리[c[3]]
            else:
                continue
        except KeyError:
            continue
        결과들.append((문장.strip(), 종류, 맞음))
    return 결과들


def 검사(자료):
    질문, 답변 = 자료.get("질문", ""), 자료.get("답변", "")
    항목 = _항목_찾기(질문)
    조건 = 순서_조건_찾기(질문, 항목)
    순서 = 답_순서_찾기(답변, 항목) if 조건 else None
    대입 = 대입하기(조건, 순서) if 순서 else []
    위반 = [f"조건 '{문장}'을(를) 만족하지 않아요 (답: {', '.join(순서)})" for 문장, 종류, 맞음 in 대입 if not 맞음]
    규칙점수 = (1.0 if 위반 else 0.0) if 대입 else None
    # 검사 AI: 조건별 만족/위반
    AI조건들 = [p for p in 검사AI_값들(자료, "유형별_검사", "조건") if isinstance(p, list)]
    AI위반 = [any(isinstance(c, dict) and str(c.get("판정", "")).strip() == "위반" for c in 목록) for 목록 in AI조건들]
    AI비율 = sum(AI위반) / len(AI위반) if AI위반 else None
    AI문장 = list(dict.fromkeys(str(c.get("내용")) for 목록 in AI조건들 for c in 목록
                               if isinstance(c, dict) and str(c.get("판정", "")).strip() == "위반" and c.get("내용")))
    if 규칙점수 is None and AI비율 is None:
        return 결과(None, 확인불가, "프로그램이 대입할 수 있는 순서 문제가 아니고, 검사 AI 결과도 없어요.",
                  세부={"항목": 항목, "조건_수": len(조건)})
    위험도 = max(x for x in (규칙점수, AI비율) if x is not None)
    근거 = []
    if 규칙점수 is not None:
        근거.append(f"답의 순서({', '.join(순서)})를 조건 {len(대입)}개에 대입했더니 {len(위반)}개를 어겼어요")
    if AI비율 is not None:
        근거.append(f"검사 AI {len(AI위반)}개 중 {sum(AI위반)}개가 '위반한 조건이 있다'고 판정했어요")
    return 결과(위험도, 근거=". ".join(근거) + ".", 문제_문장=위반 + [f"검사 AI: '{x}' 위반" for x in AI문장],
              세부={"항목": 항목, "답_순서": 순서, "대입": 대입})


