_로마 = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}


def _숫자로(글):
    글 = str(글 or "").strip()
    if re.fullmatch(r"[IVXLCDM]+", 글):
        값, 앞 = 0, 0
        for ch in reversed(글):
            v = _로마[ch]; 값 += -v if v < 앞 else v; 앞 = max(앞, v)
        return str(값)
    m = re.search(r"\d+", 글)
    return m.group(0) if m else 글.lower()


def _성들(이름들):
    성 = set()
    for 이름 in 이름들:
        이름 = re.sub(r"[.,]", " ", 이름).strip()
        if not 이름:
            continue
        if re.search(r"[가-힣]", 이름):
            성.add(이름.replace(" ", "")[:1] + "|" + 이름.replace(" ", ""))     # 한국어 이름은 이름 전체로
        else:
            조각 = [x for x in 이름.split() if len(x) > 1]
            if 조각:
                성.add(조각[-1].lower())
                성.add(조각[0].lower())
    return 성


def 항목_비교(답, 실제):
    """항목별 (답변 값, 실제 값, 같음 여부). 둘 중 하나가 비어 있으면 비교하지 않음"""
    비교 = {}
    if 답.get("저자") and 실제.get("저자"):
        답저자 = re.split(r",|·|;| and | 및 |&|외", 답["저자"])
        a, b = _성들(답저자), _성들(실제["저자"])
        한국어 = {x for x in a if "|" in x}
        같음 = bool(a & b) or any(x.split("|")[1] in "".join(실제["저자"]).replace(" ", "") for x in 한국어)
        비교["저자"] = (답["저자"], ", ".join(실제["저자"][:4]), 같음)
    if 답.get("연도") and 실제.get("연도"):
        try:
            같음 = abs(int(답["연도"]) - int(실제["연도"])) <= 1
        except ValueError:
            같음 = 답["연도"] == 실제["연도"]
        비교["연도"] = (답["연도"], 실제["연도"], 같음)
    if 답.get("학술지") and 실제.get("학술지"):
        a, b = 답["학술지"].lower(), 실제["학술지"].lower()
        비교["학술지"] = (답["학술지"], 실제["학술지"], a in b or b in a or 비슷한_정도(a, b) >= 0.6)
    for 칸 in ("권", "호"):
        if 답.get(칸) and 실제.get(칸):
            비교[칸] = (답[칸], 실제[칸], _숫자로(답[칸]) == _숫자로(실제[칸]))
    if 답.get("DOI") and 실제.get("DOI"):
        비교["DOI"] = (답["DOI"], 실제["DOI"], 답["DOI"].lower().strip() == 실제["DOI"].lower().strip())
    return 비교


def 검사(자료):
    앞결과 = ((자료.get("이전결과") or {}).get("출처 실재 확인") or {})
    표 = (앞결과.get("세부") or {}).get("자료별")
    if 표 is None:
        if 서지_도구.없다고_했나(자료.get("답변", "")):
            return 결과(None, 해당없음, "답변이 '그런 자료는 없다'고 했어요.")
        목록, _ = 서지_도구.자료_모으기(자료)
        표 = 서지_도구.여러개_찾아보기(목록[:5])
    if not 표:
        return 결과(None, 해당없음, "답변에서 인용한 자료를 찾지 못했어요.")
    있음 = [줄 for 줄 in 표 if 줄.get("판정") == "있음" and 줄.get("찾은_논문")]
    if not 있음:
        if all(줄.get("판정") == "확인 불가" for 줄 in 표):
            return 결과(None, 확인불가, "인터넷 오류로 논문 데이터베이스를 확인하지 못했어요.")
        return 결과(None, 해당없음, "실제로 있는 자료를 찾지 못해 서지 정보를 비교하지 않았어요(⑤에서 판정).")
    전체, 틀림 = 0, []
    자료별 = []
    for 줄 in 있음:
        비교 = 항목_비교(줄["자료"], 줄["찾은_논문"])
        자료별.append({"제목": 줄["자료"].get("제목"), "비교": 비교})
        전체 += len(비교)
        틀림 += [f"{칸}: 답변 '{a}' / 실제 '{b}'" for 칸, (a, b, 같음) in 비교.items() if not 같음]
    if not 전체:
        return 결과(None, 해당없음, "답변이 저자·연도·학술지·권·호를 쓰지 않아 비교할 항목이 없어요.", 세부={"자료별": 자료별})
    위험도 = len(틀림) / 전체
    근거 = f"실제로 있는 자료 {len(있음)}개의 서지 정보 {전체}항목 중 {len(틀림)}항목이 달라요."
    return 결과(위험도, 근거=근거, 문제_문장=틀림, 세부={"자료별": 자료별})


