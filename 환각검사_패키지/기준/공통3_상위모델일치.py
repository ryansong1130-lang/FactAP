import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from 도구.결과 import 결과, 확인불가, 검사AI_값들
from 도구.글_도구 import 최종답_뽑기, 핵심이_같은가

정보 = {"번호": "③", "이름": "상위 모델 답변 일치도", "맡는_환각": "사실 상충", "적용_유형": "공통", "방식": "AI 다시 묻기 + 규칙"}


def 검사(자료):
    유형 = 자료.get("유형", "")
    참고들 = [a for a in (자료.get("상위모델_답변들") or []) if a]
    if not 참고들:
        return 결과(None, 확인불가, "상위 모델의 답변을 받지 못했어요.")
    내답 = 최종답_뽑기(자료.get("답변", ""), 유형)
    참고답 = [최종답_뽑기(a, 유형) for a in 참고들]
    비교 = [핵심이_같은가(자료.get("답변", ""), a, 유형) for a in 참고들]
    방법 = "프로그램 비교"
    if any(v is None for v in 비교):                        # 프로그램으로 비교 못 한 것은 검사 AI 다수결로
        AI표 = 검사AI_값들(자료, "참고답변_일치")
        for i, v in enumerate(비교):
            if v is None:
                표 = [t[i] for t in AI표 if isinstance(t, list) and len(t) > i]
                if 표:
                    비교[i] = sum(str(x).strip() == "예" for x in 표) > len(표) / 2
        방법 = "프로그램 비교 + 검사 AI"
    비교됨 = [v for v in 비교 if v is not None]
    if not 비교됨:
        return 결과(None, 확인불가, "서술형 답이라 비교하려면 검사 AI 결과가 필요해요.",
                  세부={"사용자_최종답": 내답, "상위모델_최종답": 참고답})
    같음 = sum(비교됨)
    위험도 = 1 - 같음 / len(비교됨)
    상위끼리 = [핵심이_같은가(참고들[i], 참고들[j], 유형) for i in range(len(참고들)) for j in range(i + 1, len(참고들))]
    근거 = f"상위 모델 {len(비교됨)}개 중 {같음}개가 같은 답을 냈어요 ({방법})."
    if 상위끼리 and all(v is False for v in 상위끼리):
        근거 += " 상위 모델끼리도 답이 모두 달라 판단이 어려워요."
    문제 = [f"사용자 답: {내답} / 상위 모델 답: " + " · ".join(참고답)] if 위험도 > 0 else []
    return 결과(위험도, 근거=근거, 문제_문장=문제,
              세부={"사용자_최종답": 내답, "상위모델_최종답": 참고답, "비교": 비교})


