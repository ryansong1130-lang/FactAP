def 근거없는_문장_찾기(질문, 답변, 참고들):
    _, 의심 = 유형_분류기.지문_근거_확인(질문, 답변, 참고들, 기준=설정.지문근거_기준)
    return [(비율, 문장) for 비율, 문장 in 의심 if not re.search(설명하는_말, 문장)]


def 점수_구간(최대):
    for 하한, 점수 in ((0.7, 0.8), (0.6, 0.6), (0.5, 0.4)):
        if 최대 >= 하한:
            return 점수
    return 0.0


def 검사(자료):
    질문, 답변 = 자료.get("질문", ""), 자료.get("답변", "")
    if len(질문) < 100:
        return 결과(None, 해당없음, "질문에 지문이 없어요(질문이 너무 짧아요).")
    참고들 = [a for a in 자료.get("상위모델_답변들") or [] if a]
    의심 = 근거없는_문장_찾기(질문, 답변, 참고들)
    최대 = max((r for r, _ in 의심), default=0.0)
    규칙점수 = 점수_구간(최대)
    AI목록 = [p for p in 검사AI_값들(자료, "유형별_검사", "덧붙인_문장") if isinstance(p, list)]
    AI있음 = [bool([x for x in 목록 if str(x).strip()]) for 목록 in AI목록]
    AI비율 = sum(AI있음) / len(AI있음) if AI있음 else None
    AI문장 = list(dict.fromkeys(str(x) for 목록 in AI목록 for x in 목록 if str(x).strip()))
    위험도 = max(규칙점수, AI비율 or 0)
    근거 = f"지문에도 상위 모델 답변에도 없는 표현이 가장 많은 문장은 {최대:.0%}예요"
    if not 참고들:
        근거 += " (상위 모델 답변 없이 지문만으로 비교해서 오탐이 늘어날 수 있어요)"
    if AI비율 is not None:
        근거 += f". 검사 AI {len(AI있음)}개 중 {sum(AI있음)}개가 덧붙인 문장을 찾았어요"
    문제 = [f"{문장} (근거 없는 표현 {비율:.0%})" for 비율, 문장 in sorted(의심, reverse=True) if 비율 >= 0.5][:5]
    return 결과(위험도, 근거=근거 + ".", 문제_문장=문제 + [f"검사 AI: {x}" for x in AI문장],
              세부={"최대_비율": round(최대, 3), "의심_문장": 의심})


