정보 = {"번호": "⑥", "이름": "핵심 내용 누락·변형 확인", "맡는_환각": "입력 상충", "적용_유형": "지문 이해형", "방식": "규칙(낱말) + 검사 AI"}

_조사 = r"(?:에서는|에서|으로|에게|까지|부터|이나|이며|이고|은|는|이|가|을|를|의|에|로|와|과|도|만)$"


def 낱말들(글):
    결과들 = set()
    for w in re.findall(r"[가-힣]{2,}|[A-Za-z]{2,}|\d+(?:\.\d+)?[가-힣a-zA-Z%]*", 마크다운_지우기(글)):
        w = re.sub(_조사, "", w)
        if len(w) >= 2:
            결과들.add(w)
    return 결과들


def 빠진_핵심(질문, 답변, 참고들):
    참고낱말 = [낱말들(r) for r in 참고들 if r]
    if not 참고낱말:
        return None, []
    필요 = min(2, len(참고낱말))
    핵심 = {w for w in 낱말들(질문) if sum(w in r for r in 참고낱말) >= 필요}
    if not 핵심:
        return None, []
    빠짐 = sorted(핵심 - 낱말들(답변))
    return len(빠짐) / len(핵심), 빠짐


def 검사(자료):
    질문, 답변 = 자료.get("질문", ""), 자료.get("답변", "")
    if len(질문) < 100:
        return 결과(None, 해당없음, "질문에 지문이 없어요(질문이 너무 짧아요).")
    빠진비율, 빠짐 = 빠진_핵심(질문, 답변, 자료.get("상위모델_답변들") or [])
    규칙점수 = 0.4 if 빠진비율 is not None and 빠진비율 >= 0.4 else (0.0 if 빠진비율 is not None else None)
    AI목록 = [p for p in 검사AI_값들(자료, "유형별_검사", "빠뜨리거나_바꾼_내용") if isinstance(p, list)]
    AI있음 = [bool([x for x in 목록 if str(x).strip()]) for 목록 in AI목록]
    AI비율 = sum(AI있음) / len(AI있음) if AI있음 else None
    AI문장 = list(dict.fromkeys(str(x) for 목록 in AI목록 for x in 목록 if str(x).strip()))
    if 규칙점수 is None and AI비율 is None:
        return 결과(None, 확인불가, "상위 모델 답변과 검사 AI 결과가 없어 확인하지 못했어요.")
    위험도 = max(규칙점수 or 0, AI비율 or 0)
    근거 = []
    if 빠진비율 is not None:
        근거.append(f"지문과 상위 모델 답변에 공통으로 나오는 핵심 낱말 중 {빠진비율:.0%}가 답변에 없어요")
    if AI비율 is not None:
        근거.append(f"검사 AI {len(AI있음)}개 중 {sum(AI있음)}개가 빠뜨리거나 바꾼 내용을 찾았어요")
    문제 = ([f"빠진 핵심 낱말: {', '.join(빠짐[:8])}"] if 규칙점수 else []) + [f"검사 AI: {x}" for x in AI문장]
    return 결과(위험도, 근거=". ".join(근거) + ".", 문제_문장=문제, 세부={"빠진_비율": 빠진비율, "빠진_낱말": 빠짐})


