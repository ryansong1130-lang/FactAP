def 모델_보기_이름(모델_ID):
    """'openai/gpt-5.5' → 'gpt-5.5 (openai)'"""
    회사, _, 이름 = str(모델_ID).partition("/")
    return f"{이름} ({회사})" if 이름 else str(모델_ID)


def 모델_짧은_이름(모델_ID):
    """'openai/gpt-5.5' → 'gpt-5.5' (표 칸이 좁아서 회사 이름은 빼요)"""
    return str(모델_ID).partition("/")[2] or str(모델_ID)


def 예선_정확도():
    """예선 채점 엑셀에서 {유형: {모델코드: 정확도}} 를 계산. 파일이 없거나 읽을 수 없으면 {}"""
    try:
        import openpyxl
        책 = openpyxl.load_workbook(예선_파일, read_only=True, data_only=True)
    except Exception:
        return {}
    점수 = {"정답": 1.0, "부분 환각": 0.5}
    결과 = {}
    try:
        for 유형 in 설정.유형목록:
            if 유형 not in 책.sheetnames:
                continue
            합 = collections.defaultdict(lambda: [0.0, 0])
            for 줄 in 책[유형].iter_rows(min_row=예선_첫_답변_줄, values_only=True):
                if len(줄) < 6 or not 줄[0] or not 줄[3] or not 줄[5]:
                    continue
                합[줄[3]][0] += 점수.get(줄[5], 0.0)
                합[줄[3]][1] += 1
            결과[유형] = {코드: 점 / 개수 for 코드, (점, 개수) in 합.items() if 개수}
    finally:
        책.close()
    return 결과


def 상위모델_표(정확도=None):
    """설정.상위모델 로 '유형별 상위 3개 모델' 표(마크다운)를 만듦. 정확도가 있으면 괄호에 넣음"""
    정확도 = 정확도 or {}
    줄 = ["| 유형 | 상위 모델 1 | 상위 모델 2 | 상위 모델 3 |", "|---|---|---|---|"]
    for 유형 in 설정.유형목록:
        칸 = []
        for 코드 in 설정.상위모델.get(유형, []):
            글 = 모델_짧은_이름(설정.모델_이름.get(코드, 코드))
            값 = 정확도.get(유형, {}).get(코드)
            칸.append(f"{글} · {값:.0%}" if 값 is not None else 글)
        줄.append(f"| {유형} | " + " | ".join(칸) + " |")
    return "\n".join(줄)


def 상위모델_글(정확도=None):
    표_설명 = "#### 유형별 상위 3개 모델" + (" (· 뒤는 그 유형의 예선 정확도)" if 정확도 else "")
    쓰는_모델 = sorted({설정.모델_이름[코드] for 코드들 in 설정.상위모델.values() for 코드 in 코드들 if 코드 in 설정.모델_이름})
    회사 = "만든 회사: " + ", ".join(모델_보기_이름(m) for m in 쓰는_모델)
    return "\n".join([글_상위모델_앞.strip(), "", 표_설명, 상위모델_표(정확도), "", 회사, "", 글_상위모델_뒤.strip()])


