# -*- coding: utf-8 -*-
"""
모든 기준 파일의 '시험 사례'를 한 번에 실행해요. (API 키·인터넷 필요 없음)

  python 검증/시험_모두.py

각 기준 파일 맨 아래에 있는 시험 사례(예상 결과가 정해진 짧은 예)를 실행하고, 통과/실패 개수를 보여 줘요.
기준 파일을 고친 뒤에는 이 파일을 실행해서 원래 되던 것이 망가지지 않았는지 확인하세요.
(인터넷이 필요한 기준은 시험할 때만 '가짜 위키백과·가짜 논문 DB'를 끼워 넣어 시험해요)
"""
import glob, os, subprocess, sys

폴더 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
합계 = {"통과": 0, "실패": 0}
for 파일 in sorted(glob.glob(os.path.join(폴더, "기준", "*.py"))):
    이름 = os.path.basename(파일)
    if 이름.startswith("__"):
        continue
    r = subprocess.run([sys.executable, 파일], capture_output=True, text=True, encoding="utf-8", cwd=폴더)
    줄들 = r.stdout.splitlines()
    통과 = sum(l.startswith("통과") for l in 줄들)
    실패 = [l for l in 줄들 if l.startswith("실패")]
    합계["통과"] += 통과; 합계["실패"] += len(실패)
    상태 = "오류" if r.returncode else ("실패 있음" if 실패 else "OK")
    print(f"{이름:<22} 통과 {통과:>2}  실패 {len(실패)}  {상태}")
    for l in 실패:
        print("    ", l[:150])
    if r.returncode:
        print("    ", (r.stderr.strip().splitlines() or [""])[-1][:150])
# 점수 합치기·등급 규칙 시험 (설정.py 4번)
sys.path.insert(0, 폴더)
from 검사_실행 import 점수_합치기
def _기준(번호, 이름, 값):
    return {"정보": {"번호": 번호, "이름": 이름, "맡는_환각": "사실 상충"}, "결과": {"위험도": 값}}
_공통 = lambda a=0, b=0: [_기준("③", "상위 모델 답변 일치도", a), _기준("④", "답변 내부 일관성", b)]
# (설명, 기준결과들, 기대 등급, 기대 위험도 또는 None, 합치는 방법 또는 None=설정값)
등급_사례 = [
    ("아무 기준도 문제를 못 찾음", _공통() + [_기준("⑤", "지문 근거 확인", 0)], "문제 없음", 0.0, None),
    ("간접 비교 기준 하나만 0.33 (다른 기준 없음) → 0.33÷2", _공통(0.33), "보통", 0.165, None),
    ("코드 실행이 맞다고 함(중요도 3) + 상위 모델 1개만 다름 → 0.33÷8",
     _공통(0.33) + [_기준("⑤", "코드 직접 실행", 0), _기준("⑥", "오류 여부·출력 형식 일치", 0)], "문제 없음", 0.041, None),
    ("지문 근거 0.8(중요도 2) → 1.6÷6",
     _공통() + [_기준("⑤", "지문 근거 확인", 0.8), _기준("⑥", "핵심 내용 누락·변형 확인", 0)], "위험", 0.267, None),
    ("지문 근거 0.6(중요도 2) → 1.2÷6",
     _공통() + [_기준("⑤", "지문 근거 확인", 0.6), _기준("⑥", "핵심 내용 누락·변형 확인", 0)], "보통", 0.2, None),
    ("결정적 기준이 1 → 0.8로 올림", _공통() + [_기준("⑤", "계산 재검산", 1), _기준("⑥", "단위·조건 확인", 0)], "위험", 0.8, None),
    ("모두 해당 없음", [_기준("②", "출처-답변 연관성", None)], "판단 불가", None, None),
    ("예전 방식: 기준 하나가 0.33", _공통(0.33), "보통", 0.33, "가장 높은 값"),
    ("예전 방식: 두 기준이 함께 0.3 이상 → 0.6으로 올림", [_기준("③", "상위 모델 답변 일치도", 0.33), _기준("⑤", "지문 근거 확인", 0.4)], "위험", 0.6, "가장 높은 값"),
]
통과 = 0
for 설명, 결과들, 기대, 기대값, 방법 in 등급_사례:
    종합 = 점수_합치기(결과들, 방법)
    받음, 값 = 종합["등급"], 종합["위험도"]
    if 받음 == 기대 and (기대값 is None or (값 is not None and abs(값 - 기대값) < 0.002)):
        통과 += 1
    else:
        print(f"    실패: 등급 규칙 '{설명}' 기대 {기대}({기대값}), 결과 {받음}({값})")
합계["통과"] += 통과; 합계["실패"] += len(등급_사례) - 통과
print(f"{'점수 합치기·등급 규칙':<20} 통과 {통과:>2}  실패 {len(등급_사례) - 통과}  {'OK' if 통과 == len(등급_사례) else '실패 있음'}")
