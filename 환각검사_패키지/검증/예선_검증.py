# -*- coding: utf-8 -*-
"""
예선 자료로 기준 검증하기

예선 채점 결과(1,200개 답변, 사람이 최종 판정)를 이용해, 각 기준이 실제로 환각을 잡는지 확인해요.
API 키 없이 돌아가는 기준(프로그램 판단 기준)만 검증해요. 검사 AI가 필요한 부분은 '확인 불가'로 나와요.
(같은 예선 자료를 보면서 규칙을 다듬었기 때문에, 새 질문으로 다시 확인해야 진짜 성능을 알 수 있어요)

상황 흉내 내기
  - 검사할 답변: 예선의 각 모델 답변
  - 상위모델_답변들: 그 유형 상위 3개 모델의 같은 문항 답변 (검사할 답변이 상위 모델 것이면 그 모델은 빼고 2개)

보는 숫자 (기준마다)
  - 환각 답변(환각·부분 환각) 중 위험도 0.5 이상으로 잡은 비율 = 잡은 비율
  - 정답 답변 중 위험도 0.5 이상으로 잘못 잡은 비율 = 잘못 잡은 비율
  - 확인한 답변 수 (해당 없음·확인 불가 제외)
  - 등급별 실제 환각 비율: 기준을 모두 합친 종합 위험도로 등급(문제 없음·보통·위험)을 매겼을 때,
    각 등급에 들어간 답변 중 실제 환각(환각·부분 환각) 비율 → 등급 기준(설정.등급_기준)의 근거
    지금 방식(가중 평균)과 예전 방식(가장 높은 값)을 나란히 보여 줘요.

사용법 (패키지 폴더에서)
  python 검증/예선_검증.py                     ← 검증 폴더 안의 '예선_최종 채점 결과.xlsx'를 씀
  python 검증/예선_검증.py "다른 경로.xlsx"     ← 다른 파일을 쓰고 싶을 때
  → 화면에 표가 나오고, 검증/예선_검증_결과.xlsx 가 저장돼요.
"""
import os, sys, importlib
from collections import defaultdict
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import 설정
from 도구.결과 import 빈_자료

검증할_기준 = {   # 기준 파일 이름: 적용 유형 (None = 모든 유형)
    # API 키·인터넷 없이 돌아가는 기준만 넣었어요.
    # ①(검사 AI), ②(출처 웹 페이지), 사실형 ⑤⑥(위키백과), 출처형 ⑤⑥(논문 DB)는 키·인터넷이 있는 환경에서 따로 확인해야 해요.
    "공통3_상위모델일치": None,
    "공통4_내부일관성": None,
    "수치5_계산재검산": ["수치 계산형"],
    "수치6_단위조건": ["수치 계산형"],
    "논리5_조건대입": ["논리 추론형"],
    "논리6_임의가정": ["논리 추론형"],
    "지문5_지문근거": ["지문 이해형"],
    "지문6_핵심누락변형": ["지문 이해형"],
    "코드5_코드실행": ["코드 결과형"],
    "코드6_오류형식": ["코드 결과형"],
}


def 예선_읽기(경로):
    import openpyxl
    wb = openpyxl.load_workbook(경로, data_only=True)
    답변들 = []
    for 유형 in 설정.유형목록:
        시트 = wb[유형]
        질문 = {시트.cell(r, 1).value: 시트.cell(r, 2).value for r in range(24, 44)}
        for r in range(47, 시트.max_row + 1):
            qid, 모델, 답변, 판정, 종류 = (시트.cell(r, c).value for c in (1, 4, 5, 6, 8))
            if qid in 질문 and 모델 and 판정:
                답변들.append({"유형": 유형, "문항": qid, "모델": 모델, "질문": 질문[qid] or "",
                              "답변": str(답변 or ""), "판정": 판정, "종류": 종류 or ""})
    return 답변들


def 실행(경로):
    답변들 = 예선_읽기(경로)
    찾기 = {(a["유형"], a["문항"], a["모델"]): a for a in 답변들}
    모듈들 = {이름: importlib.import_module("기준." + 이름) for 이름 in 검증할_기준}
    통계 = defaultdict(lambda: {"환각": [], "정답": [], "확인못함": 0})
    잡은_사례 = []
    합침 = {"환각": [], "정답": []}           # 답변 하나에 대해 프로그램 기준을 모두 합친 결과
    방법들 = [설정.합치는_방법] + [m for m in 설정.등급_기준_방법별 if m != 설정.합치는_방법]
    등급표 = {m: defaultdict(lambda: [0, 0]) for m in 방법들}   # 방법 → 등급: [답변 수, 그중 실제 환각 수]
    신호표 = defaultdict(lambda: [0, 0])      # 0.3 이상을 낸 기준 수: [답변 수, 그중 실제 환각 수]
    from 검사_실행 import 점수_합치기
    for a in 답변들:
        if a["판정"] == "답변 거부":
            continue
        상위 = [m for m in 설정.상위모델[a["유형"]] if m != a["모델"]]
        참고 = [찾기[(a["유형"], a["문항"], m)]["답변"] for m in 상위 if (a["유형"], a["문항"], m) in 찾기]
        이번 = []
        for 이름, 유형들 in 검증할_기준.items():
            if 유형들 and a["유형"] not in 유형들:
                continue
            자료 = 빈_자료(a["질문"], a["답변"], 유형=a["유형"], 상위모델_답변들=참고)
            r = 모듈들[이름].검사(자료)
            칸 = 통계[이름]
            이번.append({"정보": 모듈들[이름].정보, "결과": r})
            if r["위험도"] is None:
                칸["확인못함"] += 1
                continue
            묶음 = "환각" if a["판정"] in ("환각", "부분 환각") else "정답"
            칸[묶음].append(r["위험도"])
            if r["위험도"] >= 0.5:
                잡은_사례.append([이름, a["문항"], a["모델"], a["판정"], a["종류"], r["위험도"], r["근거"][:120]])
        환각임 = a["판정"] in ("환각", "부분 환각")
        등급들 = {}
        for m in 방법들:                          # 설정.py 의 중요도·등급 경계 그대로
            g = 점수_합치기(이번, m)["등급"]
            등급들[m] = g
            등급표[m][g][0] += 1; 등급표[m][g][1] += 환각임
        합침["환각" if 환각임 else "정답"].append(등급들)
        신호 = sum(1 for x in 이번 if x["결과"]["위험도"] is not None and x["결과"]["위험도"] >= 설정.여러_신호_기준)
        신호표[min(신호, 2)][0] += 1; 신호표[min(신호, 2)][1] += 환각임
    표 = []
    print(f"{'기준':<18} {'확인한 답변':>8} {'환각 잡음':>12} {'정답 오탐':>12}")
    for 이름 in 검증할_기준:
        칸 = 통계[이름]
        h, c = 칸["환각"], 칸["정답"]
        잡음 = sum(x >= 0.5 for x in h); 오탐 = sum(x >= 0.5 for x in c)
        줄 = [이름, len(h) + len(c), f"{잡음}/{len(h)}", f"{오탐}/{len(c)}",
              f"{잡음 / len(h):.0%}" if h else "-", f"{오탐 / len(c):.0%}" if c else "-", 칸["확인못함"]]
        표.append(줄)
        print(f"{이름:<18} {줄[1]:>8} {줄[2]:>8} ({줄[4]:>4}) {줄[3]:>8} ({줄[5]:>4})")
    # 합친 결과: 답변 하나에 대해 위 기준들을 검사_실행.점수_합치기로 합쳤을 때 '위험' 등급이 나왔는지
    h, c = 합침["환각"], 합침["정답"]
    for m in 방법들:
        이름 = f"[합침] {m}" + (" (지금)" if m == 설정.합치는_방법 else " (예전)")
        잡음 = sum(1 for x in h if x[m] == "위험"); 오탐 = sum(1 for x in c if x[m] == "위험")
        줄 = [이름, len(h) + len(c), f"{잡음}/{len(h)}", f"{오탐}/{len(c)}", f"{잡음 / len(h):.0%}", f"{오탐 / len(c):.0%}", "-"]
        표.append(줄)
        print(f"{이름:<18} {줄[1]:>8} {줄[2]:>8} ({줄[4]:>4}) {줄[3]:>8} ({줄[5]:>4})")
    print("(합침 줄은 '위험' 등급이 나온 답변을 잡은 것으로 셌어요)")
    등급줄 = []
    for m in 방법들:
        표m = 등급표[m]
        전체 = sum(v[0] for v in 표m.values()); 전체환각 = sum(v[1] for v in 표m.values())
        경계 = 설정.등급_기준_방법별[m]
        print(f"\n등급별 실제 환각 비율: {m}{' (지금 쓰는 방식)' if m == 설정.합치는_방법 else ' (예전 방식, 비교용)'}"
              f", 전체 평균 {전체환각}/{전체} = {전체환각 / 전체:.1%}")
        for i, (상한, 등급) in enumerate(경계):
            n, hh = 표m.get(등급, [0, 0])
            범위 = f"{상한:g} 미만" if i == 0 else (f"{경계[i - 1][0]:g} 이상" + (f" {상한:g} 미만" if 상한 <= 1 else ""))
            줄 = [m, 등급, 범위, n, hh, f"{hh / n:.1%}" if n else "-", f"{hh / 전체환각:.0%}" if 전체환각 else "-"]
            등급줄.append(줄)
            print(f"  {등급:<6} ({범위:<13}) 답변 {n:>5}개, 그중 환각 {hh:>3}개 ({줄[5]}), 전체 환각 중 {줄[6]}")
    print("0.3 이상을 낸 기준 수별 실제 환각 비율")
    신호줄 = []
    for k, 이름 in ((0, "0개"), (1, "1개"), (2, "2개 이상")):
        n, h = 신호표.get(k, [0, 0])
        신호줄.append([이름, n, h, f"{h / n:.1%}" if n else "-"])
        print(f"  {이름:<6} 답변 {n:>5}개, 그중 환각 {h:>3}개 ({신호줄[-1][3]})")
    try:
        import openpyxl
        wb = openpyxl.Workbook(); ws = wb.active; ws.title = "요약"
        ws.append(["기준", "확인한 답변 수", "환각 중 잡은 수", "정답 중 잘못 잡은 수", "잡은 비율", "잘못 잡은 비율", "해당 없음·확인 불가"])
        for 줄 in 표: ws.append(줄)
        ws2 = wb.create_sheet("위험도 0.5 이상 답변")
        ws2.append(["기준", "문항", "모델", "채점 판정", "환각 종류", "위험도", "근거"])
        for 줄 in 잡은_사례: ws2.append(줄)
        ws3 = wb.create_sheet("등급별 실제 환각 비율")
        ws3.append(["합치는 방법", "등급", "종합 위험도 범위", "답변 수", "그중 실제 환각", "실제 환각 비율", "전체 환각 중 이 등급에 든 비율"])
        for 줄 in 등급줄: ws3.append(줄)
        ws3.append([]); ws3.append(["0.3 이상을 낸 기준 수", "답변 수", "그중 실제 환각", "실제 환각 비율"])
        for 줄 in 신호줄: ws3.append(줄)
        저장 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "예선_검증_결과.xlsx")
        wb.save(저장); print("저장:", 저장)
    except Exception as e:
        print("엑셀 저장 실패:", e)
    return 표


if __name__ == "__main__":
    기본 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "예선_최종 채점 결과.xlsx")
    경로 = sys.argv[1] if len(sys.argv) >= 2 else 기본
    if not os.path.exists(경로):
        sys.exit('사용법: python 검증/예선_검증.py "예선_최종 채점 결과.xlsx"')
    실행(경로)
